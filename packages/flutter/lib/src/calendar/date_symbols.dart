      other.titlePattern == titlePattern &&
      listEquals(other.titleMonths, titleMonths) &&
      other.mediumPattern == mediumPattern &&
      listEquals(other.mediumMonths, mediumMonths) &&
      other.hourCycle == hourCycle &&
      other.digits == digits;

