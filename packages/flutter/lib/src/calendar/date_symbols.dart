/// The names, digits, date patterns and hour cycle a locale writes dates
/// and times with, in the Gregorian calendar.
///
/// [DateSymbols.forLocale] returns the CLDR data the web adapters read
/// through `Intl.DateTimeFormat`, for the locales in its table. The shared
/// test vectors in `core/src/calendar/__vectors__/calendar-names.json` hold
/// the same table, and the core tests check it against the runtime's Intl
/// data. Pass explicit symbols for any other locale.
///
/// A pattern is literal text with tokens: `{EEEE}` the long weekday name,
/// `{d}` and `{dd}` the day, `{M}` and `{MM}` the month number, `{MMMM}`
/// the month name from the pattern's own list, and `{y}` the year, each
/// number written in [digits]. Names come from the date's year, month and
/// day alone, so the device's time zone never shifts them.
@immutable
class DateSymbols {
  /// Creates a set of date symbols.
  const DateSymbols({
    required this.weekdays,
    required this.shortWeekdays,
    required this.narrowWeekdays,
    required this.dayPattern,
    required this.dayMonths,
    required this.titlePattern,
    required this.titleMonths,
    required this.mediumPattern,
    required this.mediumMonths,
    required this.hourCycle,
    this.digits = '0123456789',
  }) : assert(digits.length == 10, 'Ten digits, 0 to 9.'),
       assert(hourCycle == 12 || hourCycle == 24, 'A 12- or 24-hour cycle.');

  /// The long weekday names, from Sunday.
  final List<String> weekdays;

  /// The short weekday names, from Sunday: the grid's column headers.
  final List<String> shortWeekdays;

  /// The narrow weekday names, from Sunday.
  final List<String> narrowWeekdays;

  /// A day's full name, its accessible name in a calendar.
  final String dayPattern;

  /// The month names [dayPattern] uses, from January; null when it writes
  /// the month as a number.
  final List<String>? dayMonths;

  /// A month's title, above its grid.
  final String titlePattern;

  /// The month names [titlePattern] uses, from January; null when it
  /// writes the month as a number.
  final List<String>? titleMonths;

  /// A date in a picker field: `Intl`'s medium date style.
  final String mediumPattern;

  /// The month names [mediumPattern] uses, from January; null when it
  /// writes the month as a number.
  final List<String>? mediumMonths;

  /// The hour cycle the locale prefers: 12 or 24.
  final int hourCycle;

  /// The ten digits, 0 to 9, of the locale's numbering system.
  final String digits;

  /// The full name of [date]: `Monday, June 1, 2026`.
  String formatDay(DateTime date) => _format(dayPattern, dayMonths, date);

  /// The title of [date]'s month: `June 2026`.
  String formatMonth(DateTime date) => _format(titlePattern, titleMonths, date);

  /// [date] as a picker field shows it: `Jun 1, 2026`.
  String formatMedium(DateTime date) =>
      _format(mediumPattern, mediumMonths, date);

  /// [value] in the locale's digits, padded to [width].
  String formatNumber(int value, [int width = 1]) {
    final text = value.toString().padLeft(width, '0');
    if (digits == '0123456789') return text;
    return String.fromCharCodes(
      text.codeUnits.map((unit) => digits.codeUnitAt(unit - 0x30)),
    );
  }

  String _format(String pattern, List<String>? months, DateTime date) =>
      pattern.replaceAllMapped(
        _token,
        (match) => switch (match.group(1)) {
          'EEEE' => weekdays[date.weekday % 7],
          'dd' => formatNumber(date.day, 2),
          'd' => formatNumber(date.day),
          'MMMM' => months![date.month - 1],
          'MM' => formatNumber(date.month, 2),
          'M' => formatNumber(date.month),
          _ => formatNumber(date.year),
        },
      );

